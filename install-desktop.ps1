# StaffForge

StaffForge is a full-stack Minecraft staff application command center.

## Features

- Profile manager
- Server application tracker
- Application status dashboard
- Answer generator
- AI-style personalization engine
- Universal browser autofill extension
- Question mapper
- Email status parser
- Resume export as PDF / Word
- Interview preparation
- Analytics dashboard
- Backup export
- Electron desktop app support
- Windows installer support

## Tech Stack

- React + Vite
- Node.js + Express
- SQLite
- Browser Extension Manifest V3
- jsPDF
- Electron
- Electron Builder

## Run Locally

Backend:

```bash
cd server
npm install
npm run dev